// Record a real, synthetic-only browser walkthrough. No account or supplier data.
import { chromium, expect } from "@playwright/test";
import fs from "node:fs/promises";
import path from "node:path";
const root=path.resolve("..");
const output=path.join(root,"docs/demo");
await fs.mkdir(output,{recursive:true});
const browser=await chromium.launch();
const context=await browser.newContext({baseURL:process.env.BASE_URL??"http://127.0.0.1:8080",viewport:{width:1440,height:1000},recordVideo:{dir:path.resolve("test-results/demo-video"),size:{width:1440,height:1000}}});
const page=await context.newPage();
const started=Date.now(),chapters=[];
const stamp=ms=>new Date(ms).toISOString().slice(11,23);
async function chapter(text,seconds=7){
 const from=Date.now()-started;
 console.log(text);
 await page.waitForTimeout(seconds*1000);
 chapters.push({from,to:Date.now()-started,text});
}
try{
 await page.goto(process.env.BASE_URL??"http://127.0.0.1:8080");
 await expect(page.getByRole("heading",{name:"Каталог 18"})).toBeVisible();
 await chapter("Volt: локальный помощник закупщика. Все товары и цены в видео синтетические.",8);
 await page.getByRole("button",{name:"Загрузить спецификацию",exact:true}).click();
 await chapter("Загружаем список. Обработка файла выполняется отдельным Go worker.");
 await page.getByLabel("Выберите файл",{exact:true}).setInputFiles(path.resolve("public/examples/specification.csv"));
 await page.getByRole("button",{name:"Проверить позиции",exact:true}).click();
 await chapter("Результат требует проверки. Отсутствующий товар не добавляется автоматически.");
 await page.getByRole("dialog").getByRole("button",{name:"Возможные замены",exact:true}).nth(0).click();
 await chapter("Правила показывают замену с совпадающими критическими характеристиками.");
 await page.getByRole("button",{name:/^DEMO-MCB-002 ·/}).click();
 await page.getByLabel("Количество 1",{exact:true}).fill("3");
 await page.getByRole("button",{name:"Сохранить черновик",exact:true}).click();
 await expect(page.getByRole("button",{name:"Сохранить черновик",exact:true})).toBeDisabled();
 await chapter("Правки сохранены в PostgreSQL. Черновик ещё не меняет корзину.");
 await page.reload();
 await page.getByRole("button",{name:"Проверить позиции",exact:true}).click();
 await expect(page.getByLabel("Выберите товар 1",{exact:true})).toHaveValue("DEMO-MCB-002");
 await chapter("После перезагрузки выбранная замена и количество восстановились.",8);
 await page.screenshot({path:path.join(root,"docs/screenshots/review-draft.png")});
 await page.getByRole("checkbox",{name:"Я проверил позиции и количество"}).check();
 await page.getByRole("button",{name:"Подготовить корзину",exact:true}).click();
 await expect(page.getByRole("dialog",{name:"Проверьте будущую корзину"})).toBeVisible();
 expect((await (await page.request.get("/api/cart")).json()).lines).toHaveLength(0);
 await chapter("Предложение отдельно от подтверждения: сервер проверит цену, остаток и ревизию.",8);
 await page.getByRole("button",{name:"Подтвердить изменения",exact:true}).click();
 await expect(page.getByRole("row").filter({hasText:"DEMO-MCB-002"})).toContainText("3 шт.");
 await chapter("Подтверждённый список: три позиции, 15 890 тенге. Реального заказа нет.");
 await page.screenshot({path:path.join(root,"docs/screenshots/cart.png")});
 const download=page.waitForEvent("download");
 await page.getByRole("link",{name:"Скачать CSV",exact:true}).click();
 await (await download).saveAs(path.resolve("test-results/demo-purchase-list.csv"));
 await chapter("CSV выгружается из серверной корзины. Доступен и XLSX.");
 await page.getByRole("link",{name:"Данные и настройки",exact:true}).click();
 await page.getByRole("radio",{name:"Поиск без модели",exact:true}).check();
 await chapter("Ollama необязательна. Основной процесс работает без скачивания модели.");
 await page.getByRole("link",{name:"Ассистент",exact:true}).click();
 await page.getByRole("textbox",{name:"Напишите вопрос…"}).fill("DEMO-MCB-002");
 await page.getByRole("button",{name:"Отправить",exact:true}).click();
 await expect(page.locator(".chat-product")).toContainText("DEMO-MCB-002");
 await chapter("Точный артикул находится без модели. Цены берутся из каталога.");
 await page.getByLabel("Язык",{exact:true}).selectOption("kk");
 await chapter("Интерфейс доступен на казахском, русском и английском.");
 await page.getByLabel("Тіл",{exact:true}).selectOption("en");
 await page.getByRole("button",{name:"Toggle theme",exact:true}).click();
 await page.getByRole("link",{name:"Catalogue",exact:true}).click();
 await chapter("Светлая и тёмная темы. Настройки сохраняются в этом браузере.");
 await page.getByRole("link",{name:"Cart",exact:true}).click();
 await page.reload();
 await expect(page.getByRole("row").filter({hasText:"DEMO-MCB-002"})).toBeVisible();
 await chapter("Корзина сохраняется после перезагрузки. Код, тесты и честные ограничения — в репозитории.",8);
 const remaining=120000-(Date.now()-started);if(remaining>0)await chapter("Демонстрация завершена. Данные синтетические; платежи и заказы не выполняются.",remaining/1000);
 const video=page.video();
 await context.close();
 await fs.copyFile(await video.path(),path.join(output,"walkthrough.webm"));
 await fs.writeFile(path.join(output,"captions.ru.vtt"),"WEBVTT\n\n"+chapters.map((c,i)=>(i+1)+"\n"+stamp(c.from)+" --> "+stamp(c.to)+"\n"+c.text+"\n").join("\n"));
 await fs.writeFile(path.join(output,"transcript.md"),"# Демонстрация Volt\n\nЗапись реального интерфейса, только синтетические данные.\n\n"+chapters.map(c=>"- "+stamp(c.from).slice(0,8)+" — "+c.text).join("\n")+"\n");
 console.log("Saved walkthrough video and captions.");
}finally{await browser.close()}

