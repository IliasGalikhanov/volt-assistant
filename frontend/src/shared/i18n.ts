export function translator(lang: Language) {
  const dict = { ru, en, kk }[lang];
  return (key: string): string => dict[key as Key] ?? key;
}
export function productName(p: Product, lang: Language) {
  return p.names?.[lang] ?? p.name;
}
export function money(n: number, lang: Language) {
  return new Intl.NumberFormat(
    { ru: "ru-KZ", kk: "kk-KZ", en: "en-US" }[lang],
    { style: "currency", currency: "KZT", maximumFractionDigits: 2 },
  ).format(n / 100);
}

export function productPrice(p: Product, lang: Language) {
  return p.read_only
    ? {
        ru: "Требует уточнения",
        kk: "Нақтылау қажет",
        en: "Requires verification",
      }[lang]
    : money(p.price_minor, lang);
}
